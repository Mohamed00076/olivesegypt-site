#!/usr/bin/env node
'use strict';

/*
 * A retired product address still lands somewhere useful.
 *
 *   node scripts/check-retired-routes.js          (part of `npm test`)
 *   node scripts/check-retired-routes.js --write  (rewrites the block)
 *
 * On 2026-10-10 the owner restructured the range by olive type: the Aggizi,
 * Toffahi and Manzanilla pages became the Green Olives page, Pepper-Stuffed
 * became Stuffed Green Olives, and Kalamata (not supplied) went. Those
 * addresses are in search results, bookmarks, old emails and the PDFs buyers
 * already downloaded, so each one answers a permanent redirect:
 *
 *   /products/<old>            -> /products/<new>          (Kalamata: /catalog)
 *   /downloads/spec-sheets/<old>-en.pdf -> the new sheet   (Kalamata: /downloads)
 *   /catalog/print?product=<old id>     -> the new sheet's id (Kalamata: the
 *                                          whole printable catalogue)
 *
 * and the same in Arabic. The rules are generated from RETIRED in
 * scripts/products.js into netlify.toml, between the BEGIN and END lines
 * below. This fails when the block is out of date, when a retired page or
 * sheet still exists on disk (so it would be served instead), and when the
 * sitemap or any page still links to a retired address.
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const { RETIRED, PRODUCTS } = require('./products');

const ROOT = path.join(__dirname, '..');
const TOML = path.join(ROOT, 'netlify.toml');
const BEGIN = '# BEGIN retired product addresses -- generated by scripts/check-retired-routes.js --write; do not edit by hand';
const END = '# END retired product addresses';

const keyOf = Object.fromEntries(PRODUCTS.map((p) => [p.dir, p.key]));
const rule = (from, to, query) =>
  `[[redirects]]\n  from = "${from}"\n  to = "${to}"\n  status = 301\n  force = true\n${query ? `  query = {product = "${query}"}\n` : ''}`;

const rules = [];
const expected = []; // [from, to] pairs, for the report
for (const r of RETIRED) {
  for (const [pre, loc] of [['', 'en'], ['/ar', 'ar']]) {
    const page = r.to ? `${pre}/products/${r.to}` : `${pre}/catalog`;
    for (const from of [`${pre}/products/${r.dir}`, `${pre}/products/${r.dir}/`]) {
      rules.push(rule(from, page)); expected.push([from, page]);
    }
    const sheet = r.to ? `${pre}/downloads/spec-sheets/${r.to}-${loc}.pdf` : `${pre}/downloads`;
    const sheetFrom = `${pre}/downloads/spec-sheets/${r.dir}-${loc}.pdf`;
    rules.push(rule(sheetFrom, sheet)); expected.push([sheetFrom, sheet]);
    if (r.key) {
      const print = r.to ? `${pre}/catalog/print?product=${keyOf[r.to]}` : `${pre}/catalog/print`;
      rules.push(rule(`${pre}/catalog/print`, print, r.key)); expected.push([`${pre}/catalog/print?product=${r.key}`, print]);
    }
  }
}
const block = `${BEGIN}\n${rules.join('\n')}${END}\n`;

let toml = fs.readFileSync(TOML, 'utf8');
const start = toml.indexOf(BEGIN);
const stop = toml.indexOf(END);

if (process.argv.includes('--write')) {
  if (start === -1) {
    const anchor = '# Hamed Green Olives, withdrawn from the range';
    if (!toml.includes(anchor)) { console.error(`netlify.toml: cannot find "${anchor}" to insert before`); process.exit(1); }
    toml = toml.replace(anchor, block + '\n' + anchor);
  } else {
    toml = toml.slice(0, start) + block + toml.slice(stop + END.length + 1);
  }
  fs.writeFileSync(TOML, toml);
  console.log(`retired-routes: wrote ${rules.length} rules to netlify.toml`);
  process.exit(0);
}

const problems = [];
if (start === -1 || stop === -1) problems.push('netlify.toml has no retired-addresses block (run with --write)');
else if (toml.slice(start, stop + END.length + 1) !== block) problems.push('netlify.toml retired-addresses block is out of date with scripts/products.js (run with --write)');

// Nothing on disk at a retired address, so the redirect is what answers.
for (const r of RETIRED) {
  for (const f of [`products/${r.dir}/index.html`, `ar/products/${r.dir}/index.html`,
    `downloads/spec-sheets/${r.dir}-en.pdf`, `ar/downloads/spec-sheets/${r.dir}-ar.pdf`]) {
    if (fs.existsSync(path.join(ROOT, f))) problems.push(`${f} still exists, so it would be served instead of the redirect`);
  }
}

// No published page, sitemap or feed links to a retired address.
const tracked = execSync('git ls-files', { cwd: ROOT }).toString().split('\n')
  .filter((f) => /\.(html|xml|txt|js|json)$/.test(f) && !/^(docs|scripts|crm|admin)\//.test(f) && !f.startsWith('netlify/') && f !== 'package.json' && f !== 'package-lock.json');
const dirs = RETIRED.map((r) => r.dir);
const linkRe = new RegExp(`/(?:products|spec-sheets)/(${dirs.join('|')})(?:[-/"#?]|-(?:en|ar)\\.pdf)`);
for (const f of tracked) {
  const s = fs.readFileSync(path.join(ROOT, f), 'utf8');
  const m = s.match(linkRe);
  if (m) problems.push(`${f} still links to a retired address (${m[1]})`);
}

if (problems.length) {
  console.error(`retired-routes: ${problems.length} problem(s):\n  ` + problems.join('\n  '));
  process.exit(1);
}
console.log(`retired-routes OK -- ${expected.length} retired addresses answer 301 to their olive type (pages, spec sheets, print-catalogue ids, both languages); none is on disk, in the sitemap or linked.`);
