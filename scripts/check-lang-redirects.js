#!/usr/bin/env node
'use strict';

/*
 * An old "?lang=ar" link lands on the Arabic page, not the English one.
 *
 *   node scripts/check-lang-redirects.js          (part of `npm test`)
 *   node scripts/check-lang-redirects.js --write  (rewrites the block)
 *
 * The site's earlier versions switched language with a query string
 * (https://olivesegypt.com/?lang=ar). Google still lists those addresses:
 * the Search Console export of 2026-10-09 (20 July to 6 October) shows
 * /?lang=ar with 3 clicks from 9 impressions, its best click rate after the
 * www homepage, and /media/new-brining-line-capacity?lang=ar. The static
 * site ignores the parameter, so a visitor who chose Arabic got the English
 * page.
 *
 * netlify.toml now carries, between the BEGIN and END lines below, one 301
 * per English page: <page>?lang=ar -> its Arabic twin. The list is derived
 * from scripts/locale-routes.js, so this check fails when a page is added or
 * removed until --write regenerates it. Left out on purpose:
 *   - the gated downloads (FUNCTION_ROUTES), served by a function whose own
 *     query parameters a redirect could drop;
 *   - /unsubscribe and /catalog/print, which read their own query string
 *     (the unsubscribe token, the print options) that the redirect would drop;
 *   - the Arabic pages themselves, so nothing can redirect to itself;
 *   - ?lang=fr and other values: there is no French site, and those pages
 *     already name their canonical English address.
 * force = true because every target path has a file, and Netlify skips a
 * redirect whose path has one unless forced.
 */

const fs = require('fs');
const path = require('path');
const routes = require('./locale-routes');

const ROOT = path.join(__dirname, '..');
const TOML = path.join(ROOT, 'netlify.toml');
const BEGIN = '# BEGIN ?lang=ar redirects -- generated by scripts/check-lang-redirects.js --write; do not edit by hand';
const END = '# END ?lang=ar redirects';

const all = routes.listRoutes();
// Pages that read their own query string: a redirect that matches on one
// query parameter does not carry the others across, so the unsubscribe
// token or the print options would be lost.
const READS_QUERY = new Set(['/unsubscribe', '/catalog/print']);
const pages = all.filter((r) => !routes.isArabic(r) && !routes.FUNCTION_ROUTES.includes(r) && !READS_QUERY.has(r));

const problems = [];
const rules = [];
for (const en of pages) {
  const ar = routes.toArabic(en);
  if (!all.includes(ar)) { problems.push(`${en} has no Arabic twin at ${ar}`); continue; }
  rules.push(`[[redirects]]\n  from = "${routes.href(en)}"\n  to = "${routes.href(ar)}"\n  status = 301\n  force = true\n  query = {lang = "ar"}\n`);
}
const block = `${BEGIN}\n${rules.join('\n')}${END}\n`;

let toml = fs.readFileSync(TOML, 'utf8');
const start = toml.indexOf(BEGIN);
const stop = toml.indexOf(END);

if (process.argv.includes('--write')) {
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  if (start === -1) {
    const anchor = '# No catch-all.';
    if (!toml.includes(anchor)) { console.error(`netlify.toml: cannot find "${anchor}" to insert before`); process.exit(1); }
    toml = toml.replace(anchor, block + '\n' + anchor);
  } else {
    toml = toml.slice(0, start) + block + toml.slice(stop + END.length + 1);
  }
  fs.writeFileSync(TOML, toml);
  console.log(`lang-redirects: wrote ${rules.length} rules to netlify.toml`);
  process.exit(0);
}

if (start === -1 || stop === -1) problems.push('netlify.toml has no ?lang=ar block (run with --write)');
else if (toml.slice(start, stop + END.length + 1) !== block) problems.push('netlify.toml ?lang=ar block is out of date with the pages on disk (run with --write)');

// No earlier rule may claim one of these paths first: Netlify uses the first match.
if (start !== -1) {
  const before = toml.slice(0, start);
  for (const en of pages) {
    if (before.includes(`from = "${routes.href(en)}"\n`)) problems.push(`an earlier rule in netlify.toml already matches ${routes.href(en)}`);
  }
}

if (problems.length) {
  console.error(`lang-redirects: ${problems.length} problem(s):\n  ` + problems.join('\n  '));
  process.exit(1);
}
console.log(`lang-redirects OK -- each of the ${rules.length} English pages sends ?lang=ar to its Arabic twin (301), generated from the route map.`);
